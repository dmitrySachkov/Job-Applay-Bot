#!/bin/sh
# Хук SessionStart и UserPromptSubmit: его вывод попадает в контекст Claude.
# Заставляет спросить сценарий в начале сессии. В автопрогоне сценарий приходит
# из scripts/daily_run.sh через JOB_BOT_SCENARIO, и вопрос не задаётся.
if [ -n "$JOB_BOT_SCENARIO" ]; then
  echo "[job-apply-bot] Сценарий этой сессии задан запуском: $JOB_BOT_SCENARIO. Вопрос о сценарии не задавай, работай по этому сценарию."
else
  echo "[job-apply-bot] Обязательное правило проекта. Если в этой сессии сценарий ещё не выбран: твоим ПЕРВЫМ действием должен быть вопрос пользователю «С чем работаем: вакансии или фаундеры?» (через AskUserQuestion, если он доступен). До ответа не вызывай skills, не читай и не меняй файлы, не выполняй просьбу из сообщения. Единственное исключение: пользователь в этом сообщении прямо назвал сценарий словами. Если сценарий в этой сессии уже выбран, не переспрашивай и работай по нему."
fi
exit 0
